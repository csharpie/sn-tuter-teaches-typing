// Generates the Fluent ATF tests (src/fluent/tests/*.now.ts) and their step
// scripts (src/fluent/tests/scripts/*.server.js) from scripts/atf/catalog.mjs.
//
// Why generate: the Fluent compiler is static. It cannot call helper
// functions or concatenate strings in .now.ts files, so the shared helper
// library (ATF_HELPERS) is prepended to each step script here and each step
// points at its script with Now.include().
//
// Run with: pnpm atf:generate
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ATF_HELPERS } from '../../src/fluent/tests/atf-helpers.ts';
import {
  TESTS, USERS, SUITES, contentFixture,
} from './catalog.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'src', 'fluent', 'tests');
const SCRIPTS = path.join(OUT, 'scripts');

const AREAS = {
  SC: { file: 'scoring', title: 'Scoring - score() (WPM-SC)' },
  LV: { file: 'log-validation', title: 'Log validation - validateLog() (WPM-LV)' },
  CO: { file: 'coach', title: 'Coach messages - chooseCoach() (WPM-CO)' },
  LC: { file: 'lifecycle', title: 'Attempt lifecycle (WPM-LC)' },
  FL: { file: 'flagging', title: 'Flagging (WPM-FL)' },
  LS: { file: 'lessons', title: 'Lessons and unlocking (WPM-LS)' },
  PB: { file: 'personal-best', title: 'Personal best (WPM-PB)' },
  PW: { file: 'profile-wpm', title: 'Profile WPM on sys_user (WPM-PW)' },
  SE: { file: 'security', title: 'Security (WPM-SE)' },
  DI: { file: 'data-integrity', title: 'Data integrity (WPM-DI)' },
};

const HEADER = '// Generated by scripts/atf/generate.mjs from scripts/atf/catalog.mjs. Do not edit;\n// change the catalog and run `pnpm atf:generate`.\n';

/** The body of a catalog function, dedented. */
// The Fluent role list for each fixture user's role.
const ROLE_LISTS = { admin: '[wpmAdminRole]', user: '[wpmUserRole]' };

function body(fn) {
  const src = fn.toString();
  const inner = src.slice(src.indexOf('{') + 1, src.lastIndexOf('}'));
  const lines = inner.replace(/^\n/, '').replace(/\s+$/, '').split('\n');
  const indent = Math.min(
    ...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length),
  );
  return lines.map((l) => l.slice(indent)).join('\n');
}

function stepScript(label, code, jasmine) {
  return `${HEADER}// ${label}
(function (outputs, steps, params, stepResult, assertEqual) {
${ATF_HELPERS.trim()}

${code}
${jasmine ? '' : 'return true;\n'}})(outputs, steps, params, stepResult, assertEqual);
${jasmine ? 'jasmine.getEnv().execute();\n' : ''}`;
}

const key = (id) => id.toLowerCase().replace('-', '_');
const lit = (s) => JSON.stringify(s);
const userVar = (name) => name.replace(/_(\w)/g, (m, c) => c.toUpperCase());

fs.rmSync(SCRIPTS, { recursive: true, force: true });
fs.mkdirSync(SCRIPTS, { recursive: true });
fs.readdirSync(OUT).forEach((f) => {
  if (f.endsWith('.now.ts')) fs.rmSync(path.join(OUT, f));
});

fs.writeFileSync(
  path.join(SCRIPTS, 'fixture-content.server.js'),
  stepScript('Content fixture (docs/ATF_TEST_SPEC.md 4.2), run as the test runner.', body(contentFixture), false),
);

const byArea = {};
TESTS.forEach((test) => {
  const area = test.id.split('-')[0];
  (byArea[area] ||= []).push(test);
});

const exportsBySuite = { unit: [], integration: [], security: [] };

Object.entries(byArea).forEach(([area, tests]) => {
  const meta = AREAS[area];
  const roleNames = new Set(
    tests.flatMap((t) => (t.users || []).map((u) => USERS[u].role)).filter(Boolean),
  );
  const roleImports = [
    roleNames.has('admin') ? 'wpmAdminRole' : null,
    roleNames.has('user') ? 'wpmUserRole' : null,
  ].filter(Boolean);
  let out = `${HEADER}import { Test } from '@servicenow/sdk/core'\n`;
  if (roleImports.length) {
    out += `import { ${roleImports.join(', ')} } from '../roles.now'\n`;
  }
  out += `\n// ${meta.title}. See docs/ATF_TEST_SPEC.md 6.\n`;

  tests.forEach((test) => {
    const k = key(test.id);
    const exportName = `atf_wpm_${k}`;
    exportsBySuite[test.suite].push({ exportName, file: meta.file });
    const lines = [];
    if (test.fixture) {
      lines.push(`        atf.server.runServerSideScript({
            $id: Now.ID['atf_wpm_${k}_fixture'],
            script: Now.include('./scripts/fixture-content.server.js'),
        })`);
    }
    const impersonated = new Set(test.steps.map((s) => s.as).filter(Boolean));
    (test.users || []).forEach((user) => {
      const u = USERS[user];
      const roles = ROLE_LISTS[u.role] || '[]';
      // Users that are only looked up by user_name need no step output.
      const target = impersonated.has(user) ? `const ${userVar(user)} = ` : '';
      lines.push(`        ${target}atf.server.createUser({
            $id: Now.ID['atf_wpm_${k}_user_${user}'],
            firstName: 'ATF',
            lastName: ${lit(u.lastName)},
            roles: ${roles},
            fieldValues: {
                user_name: ${lit(u.userName)},
                time_zone: ${lit(u.timeZone)},
                preferred_language: 'en',
            },
            impersonate: false,
        })`);
    });
    let current = null;
    test.steps.forEach((step, i) => {
      const n = i + 1;
      if (step.as && step.as !== current) {
        lines.push(`        atf.server.impersonate({ $id: Now.ID['atf_wpm_${k}_as_${n}'], user: ${userVar(step.as)}.user })`);
        current = step.as;
      }
      if (!step.as && current) {
        throw new Error(`${test.id}: a test-runner step cannot follow an impersonated one`);
      }
      const jasmine = step.jasmine !== false;
      const file = `${test.id.toLowerCase()}-${n}.server.js`;
      fs.writeFileSync(
        path.join(SCRIPTS, file),
        stepScript(`${test.id} ${test.name}, step ${n}${step.as ? ` (as ${step.as})` : ' (as the test runner)'}`, body(step.run), jasmine),
      );
      lines.push(`        atf.server.runServerSideScript({
            $id: Now.ID['atf_wpm_${k}_step_${n}'],${jasmine ? '\n            jasmineVersion: \'3.1\',' : ''}
            script: Now.include('./scripts/${file}'),
        })`);
    });
    out += `
export const ${exportName} = Test(
    {
        $id: Now.ID['atf_wpm_${k}'],
        name: ${lit(`WPM-${test.id} ${test.name}`)},
        description: ${lit(test.description)},
        active: true,
        failOnServerError: true,
    },
    (atf) => {
${lines.join('\n')}
    }
)
`;
  });
  fs.writeFileSync(path.join(OUT, `${meta.file}.now.ts`), out);
});

// Suites (docs/ATF_TEST_SPEC.md 5): three child suites under Full regression.
const imports = {};
Object.values(exportsBySuite).forEach((list) => {
  list.forEach(({ exportName, file }) => { (imports[file] ||= []).push(exportName); });
});
let suites = `${HEADER}import { TestSuite } from '@servicenow/sdk/core'\n`;
Object.entries(imports).forEach(([file, names]) => {
  suites += `import {\n${names.map((n) => `    ${n},`).join('\n')}\n} from './${file}.now'\n`;
});
suites += `
export const wpmFullRegression = TestSuite({
    $id: Now.ID['atf_wpm_suite_full_regression'],
    name: ${lit('WPM — Full regression')},
    description: 'The unit, integration, and security and integrity suites. Must pass on the test instance before promotion to production (A7.3).',
})
`;
Object.values(SUITES).forEach((suite) => {
  suites += `
export const wpmSuite_${suite.key} = TestSuite({
    $id: Now.ID['atf_wpm_suite_${suite.key}'],
    name: ${lit(suite.name)},
    description: ${lit(suite.description)},
    parent: wpmFullRegression,
    tests: [
${exportsBySuite[suite.key].map((t) => `        ${t.exportName},`).join('\n')}
    ],
})
`;
});
fs.writeFileSync(path.join(OUT, 'suites.now.ts'), suites);

const stepCount = TESTS.reduce((n, t) => n + t.steps.length, 0);
console.log(`Generated ${TESTS.length} tests (${stepCount} script steps) in ${Object.keys(byArea).length} files, plus suites.`);
